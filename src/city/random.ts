/* mulberry32 : petit générateur pseudo-aléatoire à graine. Suffisant pour de
   la génération de décor, et surtout DÉTERMINISTE : la ville est la même à
   chaque visite. */
export function rngFrom(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
